	private PlayState movementPredicate(AnimationTest<SageOfWrathEntity> event) {
		if (this.animationprocedure.equals("empty")) {
			if ((event.isMoving() || !(this.walkAnimation.speed() > -0.15F && this.walkAnimation.speed() < 0.15F))

					&& !this.isAggressive()) {
				return event.setAndContinue(RawAnimation.begin().thenLoop("animation.teller_walk"));
			}
			if (this.isAggressive() && event.isMoving()) {
				return event.setAndContinue(RawAnimation.begin().thenLoop("animation.teller_aggressive"));
			}
			return event.setAndContinue(RawAnimation.begin().thenLoop("animation.teller_idle"));
		}
		return PlayState.STOP;
	}

